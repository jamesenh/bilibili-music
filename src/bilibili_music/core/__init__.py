"""与 UI 无关的核心设施:异常体系、数据模型、HTTP 纯逻辑、磁盘缓存与播放队列。

这一层是分层依赖的**最底层**,只允许依赖标准库 —— 不导入 Qt,也不认识 ``net`` /
``api`` / ``audio`` / ``ui``。这样做的目的是让"解析、格式化、解压、原子写盘、队列排序、
任务状态机"这些最容易出错的逻辑可以脱离事件循环单测(见 ``tests/test_core.py``)。

需要平台相关能力(配置目录、数据目录等)时,由上层解析好路径再**以参数注入**,
不要为了拿一个目录而把 Qt 引进这一层(见 ``AGENTS.md`` 第 4.1 节)。

子模块分工:

* :mod:`.errors` —— 各层共用的异常体系
* :mod:`.models` —— ``Video`` / ``Page`` / ``AudioTrack`` 等领域模型
* :mod:`.headers` —— 请求头构造与 gzip/deflate 解压(纯函数)
* :mod:`.http` —— 超时、退避、限速等调优常量(只有常量,没有实现)
* :mod:`.cache` —— 音频磁盘缓存与原子写入的 ``DownloadSink``
* :mod:`.library_db` —— 本地 sqlite 库(缓存索引与播放历史共用的落点)
* :mod:`.cache_index` —— 已缓存音频的索引(让缓存可枚举)
* :mod:`.history` —— 最近播放的记录与查询(去重、倒序、按上限裁剪)
* :mod:`.download_task` —— 批量缓存任务的模型与持久化(状态机、进度、跨重启恢复)
* :mod:`.cover_cache` —— 封面图片的磁盘缓存(按 URL 落盘,带容量上限)
* :mod:`.queue` —— 播放队列与四种播放模式(纯逻辑,不碰 Qt)
* :mod:`.config` —— 应用配置的 JSON 落盘(音量、播放模式、主题、续播位置)
"""
